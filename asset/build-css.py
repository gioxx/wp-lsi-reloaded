#!/usr/bin/env python3
"""Build the plugin stylesheets and font files from their sources.

Sources:
  asset/plugin.css          widget layout, glyph base rule, tooltip styles
  asset/fontello-*/         the Fontello export (exactly one folder)

Outputs (never edit these by hand):
  css/style.css, css/style-min.css
  fonts/fontello.{eot,svg,ttf,woff,woff2}

Run from anywhere:  python3 asset/build-css.py

It also checks that every icon offered by the plugin has a glyph, so a font
export that drops an icon fails the build instead of shipping a blank icon.
"""
import glob
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_FAMILY = "lsi-fontello"
FONT_FILES = ("eot", "svg", "ttf", "woff", "woff2")


def fail(message):
    sys.exit("build-css: " + message)


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def write(path, content):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)


def minify(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{};:,>])\s*", r"\1", css)
    css = css.replace(";}", "}")
    return css.strip() + "\n"


def main():
    exports = sorted(glob.glob(os.path.join(ROOT, "asset", "fontello-*")))
    exports = [path for path in exports if os.path.isdir(path)]
    if len(exports) != 1:
        fail("expected exactly one asset/fontello-* folder, found %d" % len(exports))
    export = exports[0]

    fontello_css = read(os.path.join(export, "css", "fontello.css"))
    glyphs = re.findall(r"^\.lsicon-[a-z0-9-]+:before \{[^}]*\}", fontello_css, re.M)
    if not glyphs:
        fail("no glyph rules found in the Fontello export")

    # Every icon id offered by the plugin must have a glyph.
    php = read(os.path.join(ROOT, "lightweight-social-icons-reloaded.php"))
    icons_block = php[php.index("function lsir_icons("):]
    icon_ids = re.findall(r"'id' => '([a-z0-9-]+)'", icons_block)
    glyph_names = {re.match(r"\.lsicon-([a-z0-9-]+):before", rule).group(1) for rule in glyphs}
    missing = sorted(set(icon_ids) - glyph_names)
    if missing:
        fail("icons without a glyph in the font: " + ", ".join(missing))

    font_face = (
        "@font-face {\n"
        "  font-family: '%s';\n"
        "  src: url('../fonts/fontello.eot');\n"
        "  src: url('../fonts/fontello.eot#iefix') format('embedded-opentype'),\n"
        "       url('../fonts/fontello.woff2') format('woff2'),\n"
        "       url('../fonts/fontello.woff') format('woff'),\n"
        "       url('../fonts/fontello.ttf') format('truetype'),\n"
        "       url('../fonts/fontello.svg#fontello') format('svg');\n"
        "  font-weight: normal;\n"
        "  font-style: normal;\n"
        "}\n" % FONT_FAMILY
    )

    plugin_css = read(os.path.join(ROOT, "asset", "plugin.css"))
    plugin_css = re.sub(r"^/\*.*?\*/\s*", "", plugin_css, count=1, flags=re.S)

    header = "/* Generated by asset/build-css.py - do not edit. Source: asset/plugin.css + Fontello export. */\n"
    css = header + font_face + "\n" + plugin_css.rstrip() + "\n\n" + "\n".join(glyphs) + "\n"

    write(os.path.join(ROOT, "css", "style.css"), css)
    write(os.path.join(ROOT, "css", "style-min.css"), minify(css))

    for ext in FONT_FILES:
        shutil.copyfile(
            os.path.join(export, "font", "fontello." + ext),
            os.path.join(ROOT, "fonts", "fontello." + ext),
        )

    print("build-css: %d glyphs, %d plugin icons, fonts copied from %s"
          % (len(glyphs), len(icon_ids), os.path.basename(export)))


if __name__ == "__main__":
    main()
